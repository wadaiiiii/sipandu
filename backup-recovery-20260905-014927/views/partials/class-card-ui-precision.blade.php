<script id="sipandu-class-card-ui-precision-script">
(() => {
    if (window.__sipanduClassCardUiPrecision) return;
    window.__sipanduClassCardUiPrecision = true;

    const mark = () => {
        document.querySelectorAll('#app article').forEach((card) => {
            const participantHeading = Array.from(card.querySelectorAll('h3')).find((heading) => heading.textContent?.trim() === 'Peserta mahasiswa');
            if (!participantHeading) return;

            card.dataset.sipanduManagedClassCard = 'true';
            const body = card.children[1];
            if (!(body instanceof HTMLElement)) return;

            const header = Array.from(body.children).find((child) => child instanceof HTMLElement && child.querySelector('h2'));
            if (header instanceof HTMLElement) {
                header.dataset.sipanduManagedClassHeader = 'true';
                const info = Array.from(header.children).find((child) => child instanceof HTMLElement && child.querySelector('h2'));
                if (info instanceof HTMLElement) info.dataset.sipanduManagedClassInfo = 'true';
                const actions = Array.from(header.children).find((child) => child instanceof HTMLElement && child.querySelectorAll('a[href]').length >= 2);
                if (actions instanceof HTMLElement) actions.dataset.sipanduManagedClassActions = 'true';
            }

            const panel = participantHeading.closest('div.rounded-\\[22px\\]') ?? participantHeading.parentElement?.parentElement;
            if (!(panel instanceof HTMLElement)) return;
            panel.dataset.sipanduParticipantPanel = 'true';
            participantHeading.parentElement?.setAttribute('data-sipandu-participant-heading', 'true');

            const addRow = Array.from(panel.children).find((child) => child instanceof HTMLElement && child.querySelector('input[type="email"]'));
            if (addRow instanceof HTMLElement) addRow.dataset.sipanduParticipantAdd = 'true';

            const list = Array.from(panel.children).find((child) => child instanceof HTMLElement && child.classList.contains('overflow-auto'));
            if (list instanceof HTMLElement) {
                list.dataset.sipanduParticipantList = 'true';
                Array.from(list.children).forEach((row) => {
                    if (row instanceof HTMLElement && row.querySelector('p')) row.dataset.sipanduParticipantRow = 'true';
                });
            }
        });
    };

    let scheduled = false;
    const schedule = () => {
        if (scheduled) return;
        scheduled = true;
        requestAnimationFrame(() => {
            scheduled = false;
            mark();
        });
    };

    mark();
    const root = document.getElementById('app');
    if (root) new MutationObserver(schedule).observe(root, { childList: true, subtree: true });
})();
</script>
